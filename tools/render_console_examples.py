"""Render editable text mockups using the current console layout functions.

Run from the project root with PYTHONPATH=src. No receiver, logbook or config is read.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from kiwi_client.console_panels import main_panel_rows
from kiwi_client.reception_ui import logging_panel_rows


def render_examples(columns=174, lines=30) -> str:
    record = dict(log_id=17, ident='PH', carrier_khz=332, status='confirmed',
                  heard_utc='2026-09-26T01:02:03Z', notes='Review: hearing another ID',
                  receiver='10.0.0.43:8073', source_kind='live', event='CLE332',
                  mode='cw', tuned_khz=333.035, low_cut_hz=775, high_cut_hz=825,
                  cw_offset_hz=-800, rf_center_khz=333.035)
    history = 'CONFIRMED 2026-09-26 01:02:03Z #17 (1 entries)'
    main = main_panel_rows(columns=columns, height=lines // 2,
        radio_title='RADIO / live 10.0.0.43:8073 | SND running / W/F running',
        radio='CW    333.0350 kHz  BW   50 Hz  RSSI  -92 dBm  audio ON 65%  step 10/100 Hz',
        station=['PH / 332 kHz / 1 of 524', 'USB 333.035000 kHz', '? km / ? W / active',
                 "'Phurn' Port Huron MI USA", 'LSB=1036 USB=1035 Hz / period=8.197s'],
        reception=['CONFIRMED 2026-09-26 01:02:03Z', '#17 / 1 entries / CLE332 / live',
                   '10.0.0.43:8073', 'Note: Review: hearing another ID', 'w edit latest / W new reception'],
        table_title='STATIONS 2/524 | PH USB 333.035000 kHz | 10.0.0.43:8073 / CLE332 / live',
        table=[('  EX1', '330', 'NO', 'Example north site', '640', '8', '2026-09-20'),
               ('> PH', '332', 'CONFIRMED 2026-09-26 01:02:03Z', "'Phurn' Port Huron MI USA", '?', '8.197', '2026-09-21'),
               ('  EX2', '334', 'TENTATIVE 2026-09-26 01:05:00Z', 'Example south site', '920', '10.5', '2026-09-22')],
        filters='CLE332=on activity=active-unknown range<=offkm power>=offW sort=frequency',
        help_rows=['/ find n/N station ,/. nearby v band h/l small H/L large j/k BW w edit W new q quit',
                   'f freq m mode t/T steps c center +/- zoom a audio u auto : commands',
                   'RNA :rna store / forget / near HZ / range KM / power W / sort distance'],
        message='NEAR 1/12 anchor 333.035000 kHz ±200 Hz; PH usb 333.035000; RNA filters apply',
        telemetry='RF levels manual / RX 332.2350 kHz')
    intro = ('CURRENT CONSOLE LAYOUT — EDITABLE MOCKUP\n'
             '========================================\n'
             'Generated by tools/render_console_examples.py using the actual current renderers.\n'
             'Synthetic reception IDs/times/levels/counts; no user logbook or radio was read.\n'
             f'{columns}-column x {lines}-row terminal; one column is reserved for curses.\n'
             'Logged: personal scoped status / UTC time. Last (RNA): catalogue last-logged date.\n'
             'Edit this file freely to suggest changes. It is NOT loaded as UI configuration.\n'
             'Regenerate to a different file to preserve your edits. Use a monospace font.\n')
    sections = [('MAIN PAGE (waterfall represented by a placeholder)',
                 ['[ Waterfall history unchanged; horizontal LSB/C/USB bracket below frequency scale ]',
                  '[ Three dotted connectors run up from bracket to waterfall bottom edge only ]', *main])]
    sections.append(('LOG DIALOG — EDIT EXISTING ENTRY', logging_panel_rows(record,
        columns=columns, height=lines, entry=record['heard_utc'] + ' | ' + record['notes'],
        prompt='UTC | notes: 2026-09-26T01:02:03Z | Review: hearing another ID_',
        message='Editing latest hearing #17; time/status/notes only; Esc cancels', history=history)))
    sections.append(('LOG DIALOG — REVIEW / NOT HEARD', logging_panel_rows(record,
        columns=columns, height=lines, prompt='PH: y confirmed / t tentative / n not heard / d delete / Esc cancel',
        message='Press n to retain this entry as NOT-HEARD, excluded from reports.', history=history)))
    sections.append(('LOG DIALOG — DELETE CONFIRMATION', logging_panel_rows(record,
        columns=columns, height=lines, prompt='DELETE #17 PH? D confirms / Esc cancels',
        message='Deletion removes this reception from logs/reports; audit history remains', history=history)))
    sections.append(('MAIN LOG STATUS AFTER NOT-HEARD (example field text)',
                     ['NOT-HEARD 2026-09-26 01:02:03Z', '#17 / 1 entries / CLE332 / live']))
    return intro + '\n\n' + '\n\n'.join(title + '\n' + '\n'.join(rows) for title, rows in sections) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='new file only; default stdout; never overwrites edits')
    parser.add_argument('--columns', type=int, default=174)
    args = parser.parse_args(argv)
    if args.columns < 40:
        parser.error('--columns must be at least 40')
    text = render_examples(columns=args.columns)
    if args.output is None:
        print(text, end='')
    else:
        with args.output.open('x', encoding='utf-8') as output:
            output.write(text)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
